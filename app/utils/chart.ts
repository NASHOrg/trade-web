// Lightweight Charts™ Example: Realtime updates
// https://tradingview.github.io/lightweight-charts/tutorials/demos/realtime-updates

let randomFactor = 5 + Math.random() * 5;
const samplePoint = (i: number) =>
  i
  * (0.05
    + Math.sin(i / 1) * 0.2
    + Math.sin(i / 2) * 0.4
    + Math.sin(i / randomFactor) * 0.8
    + Math.sin(i / 50) * 0.5)
  + 5
  + i * 2;

export function generateChartData(
  numberOfCandles = 100,
  updatesPerCandle = 5,
  endDate = 0,
  interval = 1, // 1h
) {
  const createCandle = (val: number, time: number) => ({
    time,
    open: val,
    high: val,
    low: val,
    close: val,
  });

  const updateCandle = (candle: any, val: number) => ({
    time: candle.time,
    close: val,
    open: candle.open,
    low: Math.min(candle.low, val),
    high: Math.max(candle.high, val),
  });

  randomFactor = 25 + Math.random() * 25;
  let date = new Date(endDate);
  const numberOfPoints = numberOfCandles * updatesPerCandle;
  const initialData = [];
  let lastCandle;
  let previousValue = 10;
  for (let i = 0; i < numberOfPoints; ++i) {
    if (i % updatesPerCandle === 0) {
      date = new Date(date.getTime() - interval * 3600 * 1000);
    }
    const time = date.getTime() / 1000;
    let value = samplePoint(i);
    const diff = (value - previousValue) * Math.random();
    value = previousValue + diff;
    previousValue = value;
    if (i % updatesPerCandle === 0) {
      const candle = createCandle(value, time);
      lastCandle = candle;
    }
    else {
      const newCandle = updateCandle(lastCandle, value);
      lastCandle = newCandle;
      if ((i + 1) % updatesPerCandle === 0) {
        initialData.push(newCandle);
      }
    }
  }

  return initialData.reverse();
}

export function timeToLocal(originalTime: number) {
  const d = new Date(originalTime * 1000);
  return Date.UTC(d.getFullYear(), d.getMonth(), d.getDate(), d.getHours(), d.getMinutes(), d.getSeconds(), d.getMilliseconds()) / 1000;
}

